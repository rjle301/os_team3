	//How large is the unsigned data type
	//Writes to VGA 256 linear addressing
void write_pixel(unsigned x, unsigned y, unsigned c)//Means "unsigned int"
{
	unsigned wd_in_bytes;
	unsigned off;

	wd_in_bytes = g_wd;
	off = wd_in_bytes * y + x;
	vpokeb(off, c);
}


